// Что показать: главную страницу или городок. Без DOM.
//
// С 28.09.2026 на всех экранах первой открывается главная страница, а городок
// стал пасхалкой: кнопка внизу страницы и прямая ссылка /#town.
// То же правило повторено во встроенном скрипте в <head> index.html, чтобы
// страница не мигала до загрузки модулей. Тест следит, чтобы они совпадали.

export function chooseMode(hash) {
  return hash === '#town' ? 'town' : 'cv';
}
