// Какой режим показать первым: городок или обычную страницу. Без DOM.
//
// То же правило коротко повторено во встроенном скрипте в <head> index.html,
// чтобы страница не мигала обычным режимом до загрузки модулей. Тест следит,
// чтобы порог ширины там и здесь совпадал.

export const TOWN_MIN_WIDTH = 760;

// #cv и любые якоря разделов (#projects, #contacts) открывают обычный режим.
// #town открывает городок на любом экране. Без якоря решает ширина экрана:
// на телефоне первым обычный режим, городок по кнопке.
export function chooseMode(hash, viewportWidth) {
  if (hash === '#town') return 'town';
  if (hash && hash !== '#') return 'cv';
  return viewportWidth >= TOWN_MIN_WIDTH ? 'town' : 'cv';
}
